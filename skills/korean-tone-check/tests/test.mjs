import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const skill = path.join(here, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'skilltest-'));
const run = (cmd, args) => spawnSync(cmd, args, { encoding: 'utf8', env: { ...process.env, PYTHONIOENCODING: 'utf-8' } });
const fail = (m) => { console.log('FAIL ' + m); process.exit(1); };
const pickPython = (mods) => [process.env.PYTHON, 'python3', 'python'].filter(Boolean).find((p) => run(p, ['-c', `import ${mods}`]).status === 0);
const T = path.join(skill, 'scripts', 'check-tone.mjs');
const j = JSON.parse(run('node', [T, path.join(skill, 'examples', 'sample.md'), '--json']).stdout);
if (j.endingProblems !== 3) fail('sample should have 3 speech-level problems, got ' + j.endingProblems);
fs.writeFileSync(path.join(tmp, 'clean.md'), '설정은 한 번만 하면 되는데, 그다음부터는 매일 같은 시간에 자동으로 실행됩니다.\n궁금한 점이 있으면 댓글로 남겨 주세요(답은 하루 안에 드립니다).\n#자동화\n');
if (run('node', [T, path.join(tmp, 'clean.md')]).status !== 0) fail('clean polite text should pass');
fs.writeFileSync(path.join(tmp, 'num.md'), '버전 1.5 문서는 [여기](https://example.com/a.b)에서 받을 수 있습니다.\n');
const n = JSON.parse(run('node', [T, path.join(tmp, 'num.md'), '--json']).stdout);
if (n.sentences !== 1) fail('decimals/links should not split sentences');
fs.rmSync(tmp, { recursive: true, force: true });
console.log('korean-tone-check ok: speech-level gate, clean text, decimals/links/parentheses');
